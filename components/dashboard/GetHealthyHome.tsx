function printDoc(title: string, inner: string) {
  if (typeof document === "undefined") return;
  const iframe = document.createElement("iframe");
  iframe.setAttribute("aria-hidden", "true");
  iframe.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0;";
  document.body.appendChild(iframe);
  const doc = iframe.contentWindow?.document;
  if (!doc) { iframe.remove(); return; }
  doc.open();
  doc.write(`<!doctype html><html><head><meta charset="utf-8"><title>${title}</title><style>
    *{box-sizing:border-box;font-family:-apple-system,Segoe UI,Roboto,sans-serif;}
    body{margin:0;padding:34px;color:#0f3a26;}
    h1{font-size:22px;margin:0 0 2px;}
    .sub{color:#5b7266;font-size:12px;margin:0 0 20px;}
    .row{display:flex;justify-content:space-between;gap:12px;padding:9px 0;border-bottom:1px solid #e3ede7;}
    .t{font-weight:600;font-size:13px;}
    .d{color:#5b7266;font-size:12px;}
    .day{margin:14px 0;padding:12px 14px;border:1px solid #e3ede7;border-radius:12px;}
    .day h3{margin:0 0 4px;font-size:14px;}
    .chip{display:inline-block;margin:4px 5px 0 0;padding:3px 9px;background:#eef5f0;border-radius:999px;font-size:11px;}
    .foot{margin-top:26px;font-size:11px;color:#9fb0a7;}
  </style></head><body>${inner}<p class="foot">Generated by SuppAI · Get Healthy</p></body></html>`);
  doc.close();
  iframe.contentWindow?.focus();
  setTimeout(() => { iframe.contentWindow?.print(); setTimeout(() => iframe.remove(), 800); }, 300);
}
function buildDayHtml(blocks: DayBlock[], doneIds: string[]) {
  const rows = blocks
    .map((b) => `<div class="row"><div><div class="t">${b.time || "Anytime"} · ${b.title}${doneIds.includes(b.id) ? " ✓" : ""}</div><div class="d">${b.detail || ""}</div></div><div class="d">${b.kcal ? b.kcal + " kcal" : ""}</div></div>`)
    .join("");
  return `<h1>Daily plan</h1><p class="sub">Your routine for today</p>${rows}`;
}
function buildWeekHtml(routine: RoutineItem[]) {
  const days = WEEK_PLAN.map((d) => {
    const items = d.items.map((i) => `<span class="chip">${i}</span>`).join("");
    const extras = routine.filter((r) => r.day === d.key).map((r) => `<span class="chip">+ ${r.label}</span>`).join("");
    return `<div class="day"><h3>${d.label} — ${d.focus}</h3><div class="d">${d.kcal} kcal target</div><div>${items}${extras}</div></div>`;
  }).join("");
  return `<h1>Weekly plan</h1><p class="sub">Your 7-day plan</p>${days}`;
}

