function nowHHMM() {
  const now = new Date();
  return `${String(now.getHours()).padStart(2, "0")}:${String(now.getMinutes()).padStart(2, "0")}`;
}

export function GetHealthyHome() {
  const [state, setState] = useState<PlanState | null>(null);
  const [doneIds, setDoneIds] = useState<string[]>([]);
  const [blocks, setBlocks] = useState<DayBlock[]>([]);
  const [routine, setRoutine] = useState<RoutineItem[]>([]);
  const [ach, setAch] = useState<Achievements | null>(null);
  const [proc, setProc] = useState<{ active: boolean; step: number }>({ active: false, step: 0 });
  const [recipe, setRecipe] = useState<Meal | null>(null);
  const [add, setAdd] = useState<AddInit | null>(null);
  const [editMeal, setEditMeal] = useState<DayBlock | null>(null);
  const fileRef = useRef<HTMLInputElement>(null);
  const reduce = useReducedMotion();

  useEffect(() => {
    fetchPlanState().then(setState);
    fetchDoneIds().then(setDoneIds);
    fetchDayBlocks().then(setBlocks);
    fetchRoutineExtras().then(setRoutine);
    fetchAchievements().then(setAch);
  }, []);

  async function runProcessing(name: string) {
    const gap = reduce ? 250 : 800;
    setProc({ active: true, step: 0 });
    await wait(gap); setProc({ active: true, step: 1 });
    await wait(gap); setProc({ active: true, step: 2 });
    await wait(gap + 200);
    setState(await activatePlan(name));
    setBlocks(await fetchDayBlocks());
    setProc({ active: false, step: 0 });
  }

  /* A generated plan lands on the schedule in short form (dish, time, key
     numbers), grouped under Morning, Afternoon and Evening like everything else. */
  async function useMealPlanDay(day: PlannedDay, sections: PlanSection[]) {
    if (state?.status !== "active") setState(await activatePlan("your meal plan"));
    setBlocks(await applyPlanBlocks(planDayToBlocks(day, sections)));
    window.setTimeout(() => document.getElementById("today-schedule")?.scrollIntoView({ behavior: reduce ? "auto" : "smooth", block: "start" }), 120);
  }

  const browse = () => fileRef.current?.click();
  const active = state?.status === "active" && !proc.active;

  return (
    <div className="px-4 py-5 md:px-10 md:py-6">
      <input ref={fileRef} type="file" accept=".pdf,application/pdf" className="hidden" onChange={(e) => { const f = e.target.files?.[0]; if (f) runProcessing(f.name); }} />

      {proc.active ? (
        <Fade><ProcessingCard step={proc.step} /></Fade>
      ) : active ? (
        <ActivePlan
          onUseMealPlanDay={useMealPlanDay}
          state={state!}
          doneIds={doneIds}
          blocks={blocks}
          routine={routine}
          ach={ach}
          onToggle={async (id) => setDoneIds(await toggleDone(id))}
          onRemoveBlock={async (id) => setBlocks(await removeDayBlock(id))}
          onRemoveRoutine={async (id) => setRoutine(await removeRoutineItem(id))}
          onEditMeal={(b) => setEditMeal(b)}
          onOpenRecipe={setRecipe}
          onAdd={(init) => setAdd({ ...init, time: nowHHMM() })}
          onBrowse={browse}
          onReset={async () => { setState(await resetPlan()); setDoneIds([]); setBlocks(await fetchDayBlocks()); setRoutine([]); }}
          onDownloadDay={() => printDoc("SuppAI Daily plan", buildDayHtml(blocks, doneIds))}
          onDownloadWeek={() => printDoc("SuppAI Weekly plan", buildWeekHtml(routine))}
        />
      ) : (
        <EmptyPlan onUseMealPlanDay={useMealPlanDay} onBrowse={browse} onFile={(f) => { if (f) runProcessing(f.name); }} onSample={() => runProcessing("blood-report-jane.pdf")} onOpenRecipe={setRecipe} />
      )}

      <RecipeModal recipe={recipe} onClose={() => setRecipe(null)} onLog={async (r) => { setBlocks(await addDayBlock({ time: "", type: "meal", title: r.name, detail: "From recipes", kcal: r.kcal })); setRecipe(null); }} canLog={active} />

      <AddEventModal
        init={add}
        onClose={() => setAdd(null)}
        onAddDay={async (b) => { setBlocks(await addDayBlock(b)); setAdd(null); }}
        onAddRoutine={async ({ days, label, kind }) => {
          let list = routine;
          for (const day of days) list = await addRoutineItem({ day, label, kind });
          setRoutine(list);
          setAdd(null);
        }}
      />

      <MealEditor block={editMeal} onClose={() => setEditMeal(null)} onSave={async (id, patch) => { setBlocks(await updateDayBlock(id, patch)); setEditMeal(null); }} />
    </div>
  );
}

/* ------------------------------ motion + heading ------------------------------ */

function Fade({ children }: { children: React.ReactNode }) {
  const reduce = useReducedMotion();
  return <motion.div initial={reduce ? false : { opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.45, ease: EASE }}>{children}</motion.div>;
}
function Stagger({ i, children }: { i: number; children: React.ReactNode }) {
  const reduce = useReducedMotion();
  return <motion.section initial={reduce ? false : { opacity: 0, y: 16 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.5, ease: EASE, delay: reduce ? 0 : i * 0.08 }}>{children}</motion.section>;
}
