function ProgressRing({ pct }: { pct: number }) {
  const R = 40; const C = 2 * Math.PI * R; const reduce = useReducedMotion();
  return (
    <div className="relative grid h-24 w-24 shrink-0 place-items-center">
      <svg className="h-24 w-24 -rotate-90" viewBox="0 0 100 100">
        <circle cx="50" cy="50" r={R} fill="none" stroke="#0f3a26" strokeOpacity="0.08" strokeWidth="9" />
        <motion.circle cx="50" cy="50" r={R} fill="none" stroke="#006E42" strokeWidth="9" strokeLinecap="round" strokeDasharray={C} initial={reduce ? false : { strokeDashoffset: C }} animate={{ strokeDashoffset: C * (1 - pct) }} transition={{ duration: 0.9, ease: EASE }} />
      </svg>
      <p className="absolute text-[20px] font-bold tabular-nums text-[#0f3a26]">{Math.round(pct * 100)}%</p>
    </div>
  );
}

